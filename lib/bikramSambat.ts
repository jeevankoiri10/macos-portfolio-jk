export interface BSDate {
  /** BS year, e.g. 2083 */
  year: number
  /** 0-based month index into BS_MONTH_NAMES */
  month: number
  /** 1-based day of month */
  day: number
  /** Days in the current BS month */
  daysInMonth: number
}

/**
 * Convert an AD date to BS. Returns null outside the table range
 * (BS 2000-01-01 … 2090-12-30 ≈ AD 1943-2034), so callers can
 * fall back to the Gregorian view instead of crashing.
 */
export function toBikramSambat(adDate: Date): BSDate | null {
  const adUTC = Date.UTC(adDate.getFullYear(), adDate.getMonth(), adDate.getDate())
  let remaining = Math.round((adUTC - BS_EPOCH_AD_UTC) / MS_PER_DAY)
  if (remaining < 1) return null

  for (let yearIdx = 0; yearIdx < BS_MONTH_DAYS.length; yearIdx++) {
    for (let month = 0; month < 12; month++) {
      const daysInMonth = BS_MONTH_DAYS[yearIdx][month]
      if (remaining <= daysInMonth) {
        return { year: BS_EPOCH_YEAR + yearIdx, month, day: remaining, daysInMonth }
      }
      remaining -= daysInMonth
    }
  }
  return null
}
